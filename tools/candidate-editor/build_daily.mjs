import fs from 'node:fs/promises';
import path from 'node:path';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';

const inputPath = path.resolve(process.argv[2]);
const out = path.dirname(inputPath);
const input = JSON.parse(await fs.readFile(inputPath, 'utf8'));
const wb = Workbook.create();
const sheet = wb.worksheets.add('今日の候補');
const info = wb.worksheets.add('_日次情報');
const font = {name:'Arial', size:11, color:'#243B53'};
const end = input.cells.length + 5;
const literal = value => typeof value === 'string' && value.startsWith('=') ? `'${value}` : value;
sheet.showGridLines = false;
sheet.tabColor = '#243B53';
sheet.getRange(`A1:H${end}`).format.font = font;
sheet.getRange('A2').values = [['今日の候補（従来の辞書反映用）']];
sheet.getRange('A2').format.font = {...font, size:16, bold:true};
sheet.getRange('A2').format.rowHeight = 28;
sheet.getRange('A3').values = [['黄色の判断とメモを編集して保存。03の実行は辞書・配布ファイルを更新します。アプリの候補DB保存とは別です。']];
sheet.getRange('A3').format.rowHeight = 24;
sheet.getRange('A4').values = [[`候補 ${input.cells.length}語（1名につきフルネーム読み1語）`]];
sheet.getRange('D4').formulas = [[`="採用 "&COUNTIFS(C6:C${end},"採用")&"語　保留 "&COUNTIFS(C6:C${end},"保留")&"語"`]];
sheet.getRange('A4:D4').format.rowHeight = 27;
sheet.getRange(`A5:H${end}`).values = [input.headers, ...input.cells.map(row => row.map(literal))];
sheet.tables.add(`A5:H${end}`, true, 'DailyCandidates').style = 'TableStyleLight9';
sheet.getRange('A5:H5').format = {fill:'#243B53',font:{...font,bold:true,color:'#FFFFFF'}, rowHeight:30, horizontalAlignment:'center',verticalAlignment:'center'};
sheet.getRange(`A6:H${end}`).format = {font,numberFormat:'@',rowHeight:60,wrapText:true,verticalAlignment:'center',fill:'#F1F5F9'};
sheet.getRange(`C6:C${end}`).format.fill = '#FFFBEF';
sheet.getRange(`F6:F${end}`).format.fill = '#FFFBEF';
sheet.getRange(`C6:C${end}`).dataValidation = {rule:{type:'list',values:['未判断','採用','保留','不採用']}};
for (const [label, fill, color] of [['採用','#E8F4EC','#276749'],['保留','#FFF3CD','#805B10'],['不採用','#FBECEC','#9B2C2C']])
  sheet.getRange(`C6:C${end}`).conditionalFormats.add('cellIs', {operator:'equal',formula:`"${label}"`,format:{fill,font:{bold:true,color}}});
const widths = [24,22,12,58,42,30,35,44];
for (let i=0;i<widths.length;i++) sheet.getRange(`${String.fromCharCode(65+i)}:${String.fromCharCode(65+i)}`).format.columnWidth = widths[i];
sheet.getRange(`E6:E${end}`).format.font = {...font,color:'#1565C0'};
sheet.getRange(`G6:G${end}`).format.font = {...font,color:'#1565C0'};
for(let i=0;i<input.cells.length;i++) {
  const row=input.cells[i];
  const lines = Math.max(...row.map((v,j)=>Math.ceil(Array.from(String(v)).reduce((n,c)=>n+(c.charCodeAt(0)>255?2:1),0)/widths[j])));
  sheet.getRange(`A${i+6}:H${i+6}`).format.rowHeight = Math.max(60,lines*16+12);
}
sheet.freezePanes.freezeRows(5);
sheet.freezePanes.freezeColumns(3);
info.showGridLines = false;
info.getRange('A1:B1').values = [['daily-dictionary-v1',input.batch_id]];
const original = sheet.getRange('C6').values;
sheet.getRange('C6').values = [['採用']];
wb.recalculate();
const count = sheet.getRange('D4').values[0][0];
const expected = input.cells.filter((r,i)=>i===0||r[2]==='採用').length;
if (typeof count !== 'string' || !count.startsWith(`採用 ${expected}語`)) throw new Error('採用件数の計算に失敗しました');
sheet.getRange('C6').values = original;
wb.recalculate();
console.log((await wb.inspect({kind:'table',sheetId:'今日の候補',range:'A4:F8',include:'values,formulas',tableMaxRows:5,tableMaxCols:6,tableMaxCellChars:70,maxChars:2000})).ndjson);
const errors = await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!',options:{useRegex:true,maxResults:10},maxChars:1000});
console.log(errors.ndjson);
await fs.writeFile(path.join(out,'preview_daily.png'),new Uint8Array(await (await wb.render({sheetName:'今日の候補',range:`A1:F${end}`,scale:1,format:'png'})).arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(path.join(out,'今日の候補.xlsx'));
console.log(JSON.stringify({output:path.join(out,'今日の候補.xlsx'),words:input.cells.length}));
